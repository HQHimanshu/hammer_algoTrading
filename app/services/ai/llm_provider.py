def get_llm_provider(settings: Settings) -> BaseLLMProvider:
    """Factory function to instantiate the configured LLM provider."""
    provider = settings.AI_PROVIDER.lower().strip()
    if provider == "groq":
        api_key = settings.GROQ_API_KEY.strip() or settings.AI_API_KEY.strip()
        return GroqLLMProvider(
            api_key=api_key,
            model=settings.GROQ_MODEL or "llama-3.3-70b-versatile",
            base_url=settings.GROQ_BASE_URL,
            timeout_seconds=settings.REQUEST_TIMEOUT_SECONDS,
            max_output_tokens=settings.AI_MAX_OUTPUT_TOKENS,
        )
    if provider == "grok":
        api_key = settings.XAI_API_KEY.strip() or settings.AI_API_KEY.strip()
        return GrokLLMProvider(
            api_key=api_key,
            model=settings.XAI_MODEL or settings.AI_MODEL,
            base_url=settings.XAI_BASE_URL,
            timeout_seconds=settings.XAI_TIMEOUT_SECONDS,
            max_output_tokens=settings.AI_MAX_OUTPUT_TOKENS,
        )
    if provider == "gemini":
        return GeminiLLMProvider(
            api_key=settings.AI_API_KEY,
            model=settings.AI_MODEL,
            timeout_seconds=settings.AI_REQUEST_TIMEOUT_SECONDS,
        )
    return MockLLMProvider(model_name=settings.AI_MODEL)
