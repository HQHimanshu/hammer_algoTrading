import httpx
from app.config import Settings

logger = logging.getLogger("algopilot.ai.llm_provider")


class LLMProviderError(Exception):
    """Raised when an LLM provider fails or times out."""
    pass


class BaseLLMProvider(ABC):
    """Abstract interface for LLM providers."""

    @abstractmethod
    async def generate_response(self, prompt: str, system_instruction: str = "") -> str:
        """Generate response text given prompt and system instruction."""
        pass


class MockLLMProvider(BaseLLMProvider):
    """Deterministic, offline mock provider for tests and local development.

    Grounds its simulated answers in the provided evidence package without network calls.
    """

    def __init__(self, model_name: str = "mock-model"):
        self.model_name = model_name

    async def generate_response(self, prompt: str, system_instruction: str = "") -> str:
        """Produce deterministic, structured mock responses grounded in prompt content."""
        notice = "[MOCK / DEMO PROVIDER NOTICE: Generated by local deterministic MockLLMProvider for offline testing]\n\n"

        # Detect if prompt contains risk event failure
        if "REJECTED" in prompt.upper() or "CHECKS FAILED" in prompt.upper():
            return (
                notice +
                "The order was rejected by the pre-trade risk engine before submission to the exchange.\n\n"
                "Evidence:\n"
                "- Record: Risk Event\n"
                "- Outcome: Order blocked by safety controls\n\n"
                "Interpretation:\n"
                "The system evaluated the trading signal and rejected it in accordance with pre-trade risk rules.\n\n"
                "Execution:\n"
                "No order was transmitted to the exchange.\n\n"
                "Limitations:\n"
                "None noted from recorded evidence."
            )

        # Detect if prompt contains signal information
        if "BUY" in prompt.upper() or "GOLDEN CROSS" in prompt.upper():
            return (
                notice +
                "The trading strategy generated a BUY signal due to a Golden Cross where the Fast SMA crossed above the Slow SMA.\n\n"
                "Evidence:\n"
                "- Signal Action: BUY\n"
                "- RSI Filter: Confirmed within acceptable bounds (< 70)\n\n"
                "Interpretation:\n"
                "Bullish momentum indicated an entry opportunity.\n\n"
                "Execution:\n"
                "Signal was forwarded to risk management.\n\n"
                "Limitations:\n"
                "Historical market data is subject to exchange recording latency."
            )

        if "SELL" in prompt.upper() or "DEATH CROSS" in prompt.upper():
            return (
                notice +
                "The strategy generated a SELL signal due to a Death Cross where the Fast SMA crossed below the Slow SMA.\n\n"
                "Evidence:\n"
                "- Signal Action: SELL\n"
                "- RSI Filter: Confirmed above oversold threshold (> 30)\n\n"
                "Interpretation:\n"
                "Bearish momentum triggered a position exit condition.\n\n"
                "Execution:\n"
                "Position closing order was triggered.\n\n"
                "Limitations:\n"
                "None."
            )

        # General evidence summary response
        return (
            notice +
            "Based on the recorded evidence retrieved from the trading database:\n\n"
            "Summary:\n"
            "The trading system recorded the relevant events corresponding to your query.\n\n"
            "Interpretation:\n"
            "The actions taken by the engine were consistent with configured strategy and risk parameters.\n\n"
            "Limitations:\n"
            "Only recorded events within the queried database bounds were evaluated."
        )


class GeminiLLMProvider(BaseLLMProvider):
    """Google Gemini LLM provider using REST API with httpx."""

    def __init__(self, api_key: str, model: str = "gemini-1.5-flash", timeout_seconds: float = 15.0):
        if not api_key:
            raise ValueError("Gemini API key must be provided when AI_PROVIDER='gemini'")
        self.api_key = api_key
        self.model = model
        self.timeout_seconds = timeout_seconds
        self.base_url = "https://generativelanguage.googleapis.com/v1beta/models"

    async def generate_response(self, prompt: str, system_instruction: str = "") -> str:
        url = f"{self.base_url}/{self.model}:generateContent?key={self.api_key}"

        contents = []
        if system_instruction:
            contents.append({
                "role": "user",
                "parts": [{"text": f"SYSTEM INSTRUCTION: {system_instruction}"}],
            })
            contents.append({
                "role": "model",
                "parts": [{"text": "Understood. I will strictly obey these instructions and ground all answers in evidence."}],
            })

        contents.append({
            "role": "user",
            "parts": [{"text": prompt}],
        })

        payload = {
            "contents": contents,
            "generationConfig": {
                "temperature": 0.2,  # Low temperature for factual grounding
                "maxOutputTokens": 1000,
            },
        }

        try:
            async with httpx.AsyncClient(timeout=self.timeout_seconds) as client:
                response = await client.post(url, json=payload)
                if response.status_code != 200:
                    logger.error("Gemini API error (%d): %s", response.status_code, response.text)
                    raise LLMProviderError(f"Gemini API returned HTTP {response.status_code}: {response.text}")

                data = response.json()
                candidates = data.get("candidates", [])
                if not candidates:
                    raise LLMProviderError("No response candidates returned by Gemini model.")

                parts = candidates[0].get("content", {}).get("parts", [])
                if not parts:
                    raise LLMProviderError("Empty content parts in Gemini response.")

                return parts[0].get("text", "")
        except httpx.TimeoutException as exc:
            logger.error("Gemini API timeout after %.1fs", self.timeout_seconds)
            raise LLMProviderError(f"Gemini request timed out after {self.timeout_seconds} seconds") from exc
        except httpx.RequestError as exc:
            logger.error("Gemini network error: %s", exc)
            raise LLMProviderError(f"Gemini connection error: {str(exc)}") from exc


class GroqLLMProvider(BaseLLMProvider):
    """GroqCloud LLM provider using official GroqClient."""

    def __init__(
        self,
        api_key: str,
        model: str = "llama-3.3-70b-versatile",
        base_url: str = "https://api.groq.com/openai/v1",
        timeout_seconds: float = 30.0,
        max_output_tokens: int = 1000,
    ):
        from app.services.ai.groq_client import GroqClient

        self.model_name = model
        self.client = GroqClient(
            api_key=api_key,
            model=model,
            base_url=base_url,
            timeout_seconds=timeout_seconds,
            max_output_tokens=max_output_tokens,
        )

    async def generate_response(self, prompt: str, system_instruction: str = "") -> str:
        from app.services.ai.groq_client import GroqAPIError

        try:
            return await self.client.generate_chat_completion(
                prompt=prompt,
                system_instruction=system_instruction,
                temperature=0.2,
            )
        except GroqAPIError as exc:
            raise LLMProviderError(f"Groq provider error: {str(exc)}") from exc


