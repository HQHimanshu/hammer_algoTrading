class DocumentIngestionService:
    """Document repository and semantic/keyword retrieval service."""

    def __init__(
        self,
        corpus: Optional[List[KnowledgeDoc]] = None,
        embedding_service: Optional["EmbeddingService"] = None,
    ):
        from app.services.ai.embedding_service import EmbeddingService

        self._corpus: List[KnowledgeDoc] = corpus or KNOWLEDGE_CORPUS
        self._doc_map: Dict[str, KnowledgeDoc] = {d.doc_id: d for d in self._corpus}
        self.embedding_service = embedding_service or EmbeddingService()

        # Ingest and index corpus chunks into embedding service
        for doc in self._corpus:
            chunks = self.embedding_service.chunk_document(
                doc_id=doc.doc_id,
                title=doc.title,
                content=doc.content,
                category=doc.category,
                version=doc.version,
            )
            self.embedding_service.index_chunks(chunks)

    def get_document(self, doc_id: str) -> Optional[KnowledgeDoc]:
        """Retrieve document by its exact identifier."""
        return self._doc_map.get(doc_id.upper())

    def semantic_search(self, query: str, top_k: int = 3):
        """Perform semantic search using vector cosine similarity over document chunks."""
        return self.embedding_service.semantic_search(query, top_k=top_k)

    def search_documents(self, query: str, limit: int = 3) -> List[KnowledgeDoc]:
        """Search knowledge documents using keyword and token overlap scoring."""
        if not query.strip():
            return []

        tokens = set(re.findall(r"\w+", query.lower()))
        if not tokens:
            return []

        scored_docs: List[tuple[float, KnowledgeDoc]] = []

        for doc in self._corpus:
            score = 0.0
            doc_text = f"{doc.title} {doc.content} {' '.join(doc.keywords)}".lower()
            doc_tokens = set(re.findall(r"\w+", doc_text))

            # Keyword matching
            for kw in doc.keywords:
                if kw.lower() in query.lower():
                    score += 3.0

            # Token overlap
            overlap = tokens.intersection(doc_tokens)
            score += len(overlap) * 1.0

            # Title match boost
            title_tokens = set(re.findall(r"\w+", doc.title.lower()))
            score += len(tokens.intersection(title_tokens)) * 2.0

            if score > 0.0:
                scored_docs.append((score, doc))

        # Sort descending by score
        scored_docs.sort(key=lambda x: x[0], reverse=True)
        return [doc for _, doc in scored_docs[:limit]]

    def list_all_documents(self) -> List[KnowledgeDoc]:
        """Return all approved documentation records."""
        return list(self._corpus)
